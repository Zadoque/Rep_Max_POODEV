CREATE TABLE treinos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aluno_id BIGINT NOT NULL,
    rotina_origem_id BIGINT,
    inicio TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    fim TIMESTAMP(6) WITHOUT TIME ZONE,
    status VARCHAR(255) NOT NULL,
    observacoes VARCHAR(255),

    CONSTRAINT fk_treinos_aluno
        FOREIGN KEY (aluno_id)
        REFERENCES usuarios (id),

    CONSTRAINT fk_treinos_rotina_origem
        FOREIGN KEY (rotina_origem_id)
        REFERENCES rotinas_treino (id),

    CONSTRAINT ck_treinos_status
        CHECK (
            status IN (
                'EM_ANDAMENTO',
                'PAUSADO',
                'FINALIZADO'
            )
        ),

    CONSTRAINT ck_treinos_datas
        CHECK (fim IS NULL OR fim >= inicio)
);

CREATE INDEX idx_treinos_aluno_inicio
    ON treinos (aluno_id, inicio);

CREATE INDEX idx_treinos_rotina_origem
    ON treinos (rotina_origem_id);