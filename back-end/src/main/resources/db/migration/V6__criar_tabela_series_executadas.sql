CREATE TABLE series_executadas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    treino_id BIGINT NOT NULL,
    exercicio_id BIGINT NOT NULL,
    numero_serie INTEGER NOT NULL,
    repeticoes INTEGER NOT NULL,
    carga_kg NUMERIC(10, 2) NOT NULL,
    tipo_tecnica VARCHAR(255) NOT NULL,
    grupo_sequencia INTEGER,
    ordem_execucao INTEGER NOT NULL,
    etapa_drop INTEGER,

    CONSTRAINT fk_series_executadas_treino
        FOREIGN KEY (treino_id)
        REFERENCES treinos (id),

    CONSTRAINT fk_series_executadas_exercicio
        FOREIGN KEY (exercicio_id)
        REFERENCES exercicios (id),

    CONSTRAINT uk_serie_treino_ordem_execucao
        UNIQUE (treino_id, ordem_execucao),

    CONSTRAINT ck_series_numero
        CHECK (numero_serie > 0),

    CONSTRAINT ck_series_repeticoes
        CHECK (repeticoes > 0),

    CONSTRAINT ck_series_carga
        CHECK (carga_kg >= 0),

    CONSTRAINT ck_series_ordem
        CHECK (ordem_execucao > 0),

    CONSTRAINT ck_series_grupo
        CHECK (
            grupo_sequencia IS NULL
            OR grupo_sequencia > 0
        ),

    CONSTRAINT ck_series_etapa_drop
        CHECK (
            etapa_drop IS NULL
            OR etapa_drop > 0
        ),

    CONSTRAINT ck_series_tipo_tecnica
        CHECK (
            tipo_tecnica IN (
                'NORMAL',
                'BI_SET',
                'TRI_SET',
                'MONSTER_SET',
                'DROP_SET'
            )
        )
);

CREATE INDEX idx_series_executadas_exercicio
    ON series_executadas (exercicio_id);