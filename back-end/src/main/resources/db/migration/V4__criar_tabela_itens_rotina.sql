CREATE TABLE itens_rotina (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rotina_id BIGINT NOT NULL,
    exercicio_id BIGINT NOT NULL,
    ordem INTEGER NOT NULL,
    quantidade_series INTEGER NOT NULL,

    CONSTRAINT fk_itens_rotina_rotina
        FOREIGN KEY (rotina_id)
        REFERENCES rotinas_treino (id),

    CONSTRAINT fk_itens_rotina_exercicio
        FOREIGN KEY (exercicio_id)
        REFERENCES exercicios (id),

    CONSTRAINT uk_item_rotina_ordem
        UNIQUE (rotina_id, ordem),

    CONSTRAINT ck_itens_rotina_ordem
        CHECK (ordem > 0),

    CONSTRAINT ck_itens_rotina_quantidade_series
        CHECK (quantidade_series > 0)
);

CREATE INDEX idx_itens_rotina_exercicio
    ON itens_rotina (exercicio_id);