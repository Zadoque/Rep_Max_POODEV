CREATE TABLE exercicios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    grupo_muscular VARCHAR(255) NOT NULL,
    descricao VARCHAR(255),
    instrucoes_execucao VARCHAR(255) NOT NULL,
    url_midia VARCHAR(255),
    ativo BOOLEAN NOT NULL,

    CONSTRAINT ck_exercicios_grupo_muscular
        CHECK (
            grupo_muscular IN (
                'PEITO',
                'COSTAS',
                'OMBROS',
                'BICEPS',
                'TRICEPS',
                'QUADRICEPS',
                'POSTERIOR_COXA',
                'GLUTEOS',
                'PANTURRILHAS',
                'ABDOMEN'
            )
        )
);